export function translate(locale: Locale, message: Message, values?: MessageValues): string {
  const text = typeof message === "string" ? message : message.text;
  const parameters = typeof message === "string" ? values : message.values;
  const translated = locale === "vi" && Object.hasOwn(vietnamese, text) ? vietnamese[text] : text;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => parameters && Object.hasOwn(parameters, key) ? String(parameters[key]) : match);
}
