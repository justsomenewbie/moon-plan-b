#!/usr/bin/env bash
# Put the lunarnav API behind an existing nginx (instead of Caddy) and get a Let's Encrypt certificate.
# Run as root on the VPS (safe to re-run):
#   bash setup-nginx-api.sh api.example.org [email]
# Needs: nginx + certbot (python3-certbot-nginx) installed; DNS of the domain pointing at this VPS
# (directly or through Cloudflare proxy). Writes:
#   /etc/nginx/conf.d/cloudflare-realip.conf   trusted Cloudflare ranges -> real client IP
#   /etc/nginx/sites-available/<domain>         from nginx-api.conf
set -euo pipefail

DOMAIN="${1:-}"
EMAIL="${2:-}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
[ "$(id -u)" = 0 ] || die "run as root"
[[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || die "usage: $0 <domain> [email]"
command -v nginx >/dev/null || apt-get install -y nginx
command -v certbot >/dev/null || DEBIAN_FRONTEND=noninteractive apt-get install -y certbot python3-certbot-nginx

# Cloudflare real IP (refresh the ranges every run; keep the old file if the download fails)
tmp="$(mktemp)"
if { echo "# generated by setup-nginx-api.sh $(date -u +%FT%TZ) from https://www.cloudflare.com/ips-v4 and ips-v6"
     for v in 4 6; do curl -fsS --max-time 15 "https://www.cloudflare.com/ips-v$v" | sed -e '/^\s*$/d' -e 's/^/set_real_ip_from /' -e 's/$/;/'; echo; done
     echo "real_ip_header CF-Connecting-IP;"; } > "$tmp" && grep -q set_real_ip_from "$tmp"; then
  install -m 0644 "$tmp" /etc/nginx/conf.d/cloudflare-realip.conf
else
  echo "WARNING: could not download Cloudflare IP ranges; keeping the existing real-IP config (if any)" >&2
fi
rm -f "$tmp"

CONF="/etc/nginx/sites-available/$DOMAIN"
if [ -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ] && [ -f "$CONF" ]; then
  echo "certificate and site exist: re-applying the proxy locations only via certbot reinstall"
fi
[ -f "$CONF" ] && cp -p "$CONF" "$CONF.bak"
sed -e 's/\r$//' -e "s/__API_DOMAIN__/$DOMAIN/g" "$SCRIPT_DIR/nginx-api.conf" > "$CONF"
# the map block may only be defined once across all sites
if grep -rqs 'map \$http_upgrade \$connection_upgrade' /etc/nginx/nginx.conf /etc/nginx/conf.d/ \
   $(ls /etc/nginx/sites-enabled/* 2>/dev/null | grep -v "/$DOMAIN\$"); then
  python3 - "$CONF" <<'PY'
import re, sys
p = sys.argv[1]
s = open(p).read()
s = re.sub(r"map \$http_upgrade \$connection_upgrade \{.*?\}\n", "", s, count=1, flags=re.S)
open(p, "w").write(s)
PY
fi
ln -sf "$CONF" "/etc/nginx/sites-enabled/$DOMAIN"
if ! nginx -t; then
  [ -f "$CONF.bak" ] && mv "$CONF.bak" "$CONF" || rm -f "$CONF" "/etc/nginx/sites-enabled/$DOMAIN"
  die "nginx -t failed; previous config restored"
fi
systemctl reload nginx

CB=(certbot --nginx -d "$DOMAIN" --non-interactive --agree-tos --redirect --keep-until-expiring)
if [ -n "$EMAIL" ]; then CB+=(-m "$EMAIL"); else CB+=(--register-unsafely-without-email); fi
if "${CB[@]}"; then echo "HTTPS ok for $DOMAIN"; else echo "WARNING: certbot failed; API stays on HTTP for now" >&2; fi
nginx -t && systemctl reload nginx
curl -fsS http://127.0.0.1:3000/api/v1/health >/dev/null && echo "API on 127.0.0.1:3000 OK" || echo "WARNING: API not answering on 127.0.0.1:3000 (pm2 status?)" >&2
if [ -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ]; then
  curl -fsS --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/api/v1/health" >/dev/null && echo "nginx HTTPS proxy check OK" || echo "WARNING: nginx HTTPS proxy check failed" >&2
else
  curl -fsS -H "Host: $DOMAIN" http://127.0.0.1/api/v1/health >/dev/null && echo "nginx HTTP proxy check OK" || echo "WARNING: nginx HTTP proxy check failed" >&2
fi
